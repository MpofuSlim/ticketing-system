#!/usr/bin/env bash
# (Re)generate the host nginx's Cloudflare real-IP snippet from Cloudflare's
# published edge ranges, then test and reload nginx.
#
# The api-gateway keys every per-IP rate limit on the X-Real-IP header that
# nginx sets from $remote_addr (deploy/k8s/README.md §3). $remote_addr is the
# real client only because of this snippet: nginx takes CF-Connecting-IP as the
# client address ONLY when the TCP peer is a Cloudflare edge listed here. Any
# other peer keeps its own address, so a caller cannot choose its key.
#
# Usage (on each host, from the repo checkout):
#   sudo ./scripts/cloudflare-real-ip.sh            # write, nginx -t, reload
#   ./scripts/cloudflare-real-ip.sh --print         # print the snippet only
#
# Refresh: re-run on BOTH hosts every quarter, and whenever Cloudflare
# announces a range change. A stale list never lets a caller choose its
# address: a request from an unlisted edge keeps that edge's address, so its
# callers share one bucket (more 429s) until the list is refreshed.
#
# CLOUDFLARE_REAL_IP_CONF overrides the target path
# (default /etc/nginx/snippets/cloudflare-real-ip.conf).

set -euo pipefail

OUT="${CLOUDFLARE_REAL_IP_CONF:-/etc/nginx/snippets/cloudflare-real-ip.conf}"
V4_URL="https://www.cloudflare.com/ips-v4"
V6_URL="https://www.cloudflare.com/ips-v6"

PRINT_ONLY=false
if [[ "${1:-}" == "--print" ]]; then
    PRINT_ONLY=true
elif [[ $# -gt 0 ]]; then
    echo "usage: $0 [--print]" >&2
    exit 2
fi

# One CIDR per line, nothing else. Anything that is not a CIDR (an HTML error
# page, a proxy's block page, an empty body) aborts before nginx is touched.
fetch_ranges() {
    local url="$1" pattern="$2" min="$3" ranges
    # Checked explicitly: errexit does not reach into a command substitution.
    if ! ranges=$(curl -fsS --max-time 20 "$url"); then
        echo "FAILED: could not fetch $url; nginx left unchanged." >&2
        exit 1
    fi
    ranges=$(printf '%s\n' "$ranges" | tr -d '\r' | sed '/^[[:space:]]*$/d')
    if [[ -z "$ranges" ]] || printf '%s\n' "$ranges" | grep -Evq "$pattern"; then
        echo "FAILED: $url did not return CIDR ranges only; nginx left unchanged." >&2
        exit 1
    fi
    if [[ $(printf '%s\n' "$ranges" | wc -l) -lt "$min" ]]; then
        echo "FAILED: $url returned fewer than $min ranges; nginx left unchanged." >&2
        exit 1
    fi
    printf '%s\n' "$ranges"
}

V4=$(fetch_ranges "$V4_URL" '^([0-9]{1,3}\.){3}[0-9]{1,3}/[0-9]{1,2}$' 5)
V6=$(fetch_ranges "$V6_URL" '^[0-9A-Fa-f:]+/[0-9]{1,3}$' 3)

TMP=$(mktemp)
trap 'rm -f "$TMP"' EXIT
{
    echo "# Cloudflare edge ranges. GENERATED by scripts/cloudflare-real-ip.sh"
    echo "# on $(date -u +%Y-%m-%dT%H:%M:%SZ) from $V4_URL and $V6_URL."
    echo "# Do not edit by hand: re-run the script (deploy/k8s/README.md §3)."
    echo "# CF-Connecting-IP becomes \$remote_addr only when the TCP peer is one of these."
    while read -r cidr; do echo "set_real_ip_from $cidr;"; done <<< "$V4"
    while read -r cidr; do echo "set_real_ip_from $cidr;"; done <<< "$V6"
    echo "real_ip_header CF-Connecting-IP;"
} > "$TMP"

if $PRINT_ONLY; then
    cat "$TMP"
    exit 0
fi

if [[ $EUID -ne 0 ]]; then
    echo "FAILED: run with sudo to write $OUT and reload nginx (or use --print)." >&2
    exit 1
fi

mkdir -p "$(dirname "$OUT")"
BACKUP=""
if [[ -f "$OUT" ]]; then
    echo "Changes against the current $OUT (comments ignored):"
    diff <(grep -v '^#' "$OUT") <(grep -v '^#' "$TMP") || true
    BACKUP="$OUT.bak"
    cp -p "$OUT" "$BACKUP"
fi
install -m 0644 "$TMP" "$OUT"

if nginx -t; then
    nginx -s reload
    echo "OK: $(grep -c '^set_real_ip_from' "$OUT") Cloudflare ranges in $OUT; nginx reloaded."
else
    if [[ -n "$BACKUP" ]]; then
        cp -p "$BACKUP" "$OUT"
    else
        rm -f "$OUT"
    fi
    echo "FAILED: nginx -t rejected the new snippet; the previous one is restored and nginx was not reloaded." >&2
    exit 1
fi
